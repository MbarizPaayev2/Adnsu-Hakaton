import { SUPPORTED_PORTALS, type PortalKey } from './portals';
import type { Answers } from './field-resolver';
import type { AgentConfig } from './agent.config';

export const CONSENT_VERSION = 2; // 2: the consent may name per-vacancy approved letters
export const ASK_CATEGORIES = ['salary', 'work_authorization', 'notice', 'cover', 'location', 'org', 'phone', 'unknown'] as const;
const SLUG = /^[a-z0-9][a-z0-9-]{0,60}$/;
const CURRENCIES = ['AZN', 'USD', 'EUR', 'GBP', 'RUB', 'TRY'];
const ARRANGEMENTS = ['Remote', 'Hybrid', 'On-site'];
const LEVELS = ['Junior', 'Mid-level', 'Senior', 'Lead'];

export interface Scope {
  name: string;
  mode: 'ASSISTED' | 'AUTONOMOUS';
  portals: PortalKey[];
  employerAllow: string[];
  employerDeny: string[];
  targetRoles: string[];
  locations: string[];
  criteria: { minScore: number; workArrangement?: string; experienceLevel?: string; mustInclude: string[]; mustExclude: string[] };
  resumeId: string;
  coverNote: string | null;
  /** Send, where the candidate has approved one for the vacancy, that letter instead of the campaign's single note. Never a letter generated by the agent. */
  useApprovedLetters: boolean;
  answers: Answers;
  alwaysAsk: string[];
  dailyLimit: number;
  expiresAt: string;
}

type Result = { ok: true; scope: Scope } | { ok: false; errors: string[] };
const str = (v: unknown, max: number) => (typeof v === 'string' ? v.replace(/\s+/g, ' ').trim().slice(0, max) : '');
const list = (v: unknown, max: number, each: number, lower = true) =>
  Array.isArray(v) ? [...new Set(v.map((x) => str(x, each)).filter(Boolean).map((x) => (lower ? x.toLowerCase() : x)))].slice(0, max) : [];
const url = (v: unknown) => {
  const s = str(v, 300);
  if (!s) return null;
  try { const u = new URL(s); return (u.protocol === 'https:' || u.protocol === 'http:') && !u.username && !u.password ? s : undefined; } catch { return undefined; }
};

/** Validates and normalises what the candidate is asked to authorise. Pure: the same input always gives the same scope (and so the same consent hash). */
export function normalizeScope(raw: unknown, now: Date, cfg: Pick<AgentConfig, 'userDailyLimit' | 'maxCampaignDays'>): Result {
  const errors: string[] = [];
  const r = (raw && typeof raw === 'object' ? raw : {}) as Record<string, any>;
  const name = str(r.name, 80);
  if (!name) errors.push('name');
  const mode = r.mode === 'AUTONOMOUS' ? 'AUTONOMOUS' : r.mode === 'ASSISTED' ? 'ASSISTED' : null;
  if (!mode) errors.push('mode');
  const portals = [...new Set(list(r.portals, 5, 20))].filter((p): p is PortalKey => (SUPPORTED_PORTALS as string[]).includes(p));
  if (!portals.length || (Array.isArray(r.portals) && portals.length !== new Set(list(r.portals, 5, 20)).size)) errors.push('portals');
  const employerAllow = list(r.employerAllow, 50, 61);
  if (!employerAllow.length || employerAllow.some((e) => !SLUG.test(e))) errors.push('employerAllow');
  const employerDeny = list(r.employerDeny, 50, 61);
  if (employerDeny.some((e) => !SLUG.test(e) || employerAllow.includes(e))) errors.push('employerDeny');
  const targetRoles = list(r.targetRoles, 20, 60).filter((t) => t.length >= 2);
  if (!targetRoles.length) errors.push('targetRoles');
  const locations = list(r.locations, 20, 60);
  const c = (r.criteria && typeof r.criteria === 'object' ? r.criteria : {}) as Record<string, any>;
  const minScore = c.minScore === undefined ? 0.5 : Number(c.minScore);
  if (!Number.isFinite(minScore) || minScore < 0 || minScore > 1) errors.push('criteria.minScore');
  const workArrangement = c.workArrangement ? str(c.workArrangement, 20) : undefined;
  if (workArrangement && !ARRANGEMENTS.includes(workArrangement)) errors.push('criteria.workArrangement');
  const experienceLevel = c.experienceLevel ? str(c.experienceLevel, 20) : undefined;
  if (experienceLevel && !LEVELS.includes(experienceLevel)) errors.push('criteria.experienceLevel');
  const resumeId = str(r.resumeId, 40);
  if (!resumeId) errors.push('resumeId');
  const coverNote = typeof r.coverNote === 'string' && r.coverNote.trim() ? r.coverNote.trim().slice(0, 3000) : null;

  const a = (r.answers && typeof r.answers === 'object' ? r.answers : {}) as Record<string, any>;
  const email = str(a.email, 200).toLowerCase();
  if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) errors.push('answers.email');
  const links: NonNullable<Answers['links']> = {};
  for (const k of ['linkedin', 'github', 'twitter', 'portfolio', 'other'] as const) {
    const v = url(a.links?.[k]);
    if (v === undefined) errors.push(`answers.links.${k}`); else if (v) links[k] = v;
  }
  let salary: Answers['salary'] = null;
  if (a.salary) {
    const amount = Number(a.salary.amount), currency = str(a.salary.currency, 3).toUpperCase();
    if (!Number.isFinite(amount) || amount <= 0 || amount > 10_000_000 || !CURRENCIES.includes(currency)) errors.push('answers.salary');
    else salary = { amount: Math.round(amount), currency, ...(a.salary.period ? { period: str(a.salary.period, 20) } : {}) };
  }
  const workAuthorization = a.workAuthorization === 'yes' || a.workAuthorization === 'no' ? a.workAuthorization : null;
  const answers: Answers = {
    fullName: str(a.fullName, 120) || null, email: email || null, phone: str(a.phone, 40) || null, location: str(a.location, 120) || null, currentCompany: str(a.currentCompany, 120) || null,
    links, workAuthorization, salary, noticePeriod: str(a.noticePeriod, 100) || null,
  };
  if (!answers.fullName) errors.push('answers.fullName');
  if (!answers.email) errors.push('answers.email');
  const alwaysAsk = list(r.alwaysAsk, 10, 30).filter((x) => (ASK_CATEGORIES as readonly string[]).includes(x));
  const dailyLimit = Number(r.dailyLimit);
  if (!Number.isInteger(dailyLimit) || dailyLimit < 1 || dailyLimit > cfg.userDailyLimit) errors.push('dailyLimit');
  const exp = typeof r.expiresAt === 'string' ? new Date(r.expiresAt) : null;
  if (!exp || Number.isNaN(exp.getTime()) || exp.getTime() < now.getTime() + 3_600_000 || exp.getTime() > now.getTime() + cfg.maxCampaignDays * 86_400_000) errors.push('expiresAt');
  if (errors.length || !mode || !exp) return { ok: false, errors: [...new Set(errors)] };
  return {
    ok: true,
    scope: {
      name, mode, portals: portals.sort(), employerAllow: [...employerAllow].sort(), employerDeny: [...employerDeny].sort(), targetRoles: [...targetRoles].sort(), locations: [...locations].sort(),
      criteria: { minScore: Math.round(minScore * 100) / 100, ...(workArrangement ? { workArrangement } : {}), ...(experienceLevel ? { experienceLevel } : {}), mustInclude: list(c.mustInclude, 20, 60), mustExclude: list(c.mustExclude, 20, 60) },
      resumeId, coverNote, useApprovedLetters: r.useApprovedLetters === true, answers, alwaysAsk: [...alwaysAsk].sort(), dailyLimit, expiresAt: exp.toISOString(),
    },
  };
}
